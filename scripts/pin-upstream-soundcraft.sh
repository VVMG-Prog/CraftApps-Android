#!/usr/bin/env bash
# Re-pin the SoundCraft upstream to a new tag and re-apply the port's changes.
# Usage: scripts/pin-upstream-soundcraft.sh <tag>   (e.g. scripts/pin-upstream-soundcraft.sh v0.10.0)
#
# The port keeps exactly these changes inside upstream/:
#   1. apps/soundcraft-android/  — the port crate (not part of upstream; copied
#      from the old checkout into the new one by this script)
#   2. Cargo.toml                — default-members excludes the android crate
#      (its android-activity/JNI deps don't build for host targets)
#   3. Cargo.toml                — [patch.crates-io] points android-activity at
#      the vendored copy (../../vendor/android-activity)
#   4. Cargo.lock                — gains the port's extra deps; regenerated by
#      cargo on the next build, not hand-edited.
#
# SoundCraft needs NO ui-egui patch: that crate depends on egui only (never
# eframe), so the accesskit gate the other ports need does not apply.
#
# Everything is LOCAL. This script never pushes.
set -euo pipefail

[ $# -eq 1 ] || { echo "usage: $0 <tag>" >&2; exit 1; }
TAG="$1"
APP="soundcraft"
MONOREPO="$HOME/workspace/craftapps-android"
UPSTREAM_DIR="$MONOREPO/$APP/upstream"
UPSTREAM_REPO="https://github.com/storytold/soundcraft.git"
WORK="/tmp/pin-$APP-$$"

[ -f "$UPSTREAM_DIR/apps/$APP-android/src/lib.rs" ] || {
    echo "FATAL: apps/$APP-android not found in $UPSTREAM_DIR — cannot pin" >&2
    exit 1
}

echo "cloning $UPSTREAM_REPO at $TAG..."
git clone --depth 1 --branch "$TAG" "$UPSTREAM_REPO" "$WORK/pristine" 2>&1 | tail -1

cp -r "$UPSTREAM_DIR/apps/$APP-android" "$WORK/pristine/apps/"
[ -f "$WORK/pristine/apps/$APP-android/src/lib.rs" ] || {
    echo "FATAL: port crate copy failed" >&2; rm -rf "$WORK"; exit 1
}

cd "$WORK/pristine"

# re-apply the default-members exclusion
if ! grep -q 'stays out of the default set' Cargo.toml; then
    python3 - <<'EOF'
p = 'Cargo.toml'
s = open(p).read()
old = 'default-members = ["crates/*", "apps/*", "xtask"]'
assert old in s, "default-members line not found; patch Cargo.toml by hand"
new = ('# The Android port is built explicitly (`cargo build -p soundcraft-android\n'
       '# --target aarch64-linux-android`); its android-activity / JNI deps don\'t\n'
       '# build for host targets, so it stays out of the default set (the other\n'
       '# suite ports do the same).\n'
       'default-members = ["crates/*", "apps/soundcraft", "apps/soundcraft-cli", "apps/soundcraft-web", "xtask"]')
s = s.replace(old, new, 1)
open(p, 'w').write(s)
print("re-applied default-members exclusion")
EOF
fi

# re-apply the vendored android-activity patch
if ! grep -q 'vendor/android-activity' Cargo.toml; then
    cat >> Cargo.toml <<'EOF'

# Android port: the vendored android-activity (S Pen stylus patch), as in
# every CraftApps suite port.
[patch.crates-io]
android-activity = { path = "../../vendor/android-activity" }
EOF
    echo "re-applied the android-activity patch"
fi

# unified versioning: VERSION_NAME is managed at release time
# (see scripts/release.sh), NOT bumped here. The pin only updates
# upstream source; the port keeps its current unified version.
CURVN="$(grep -oP 'pub const VERSION_NAME: &str = "\K[^"]+' "apps/$APP-android/src/lib.rs")"
echo "VERSION_NAME stays at $CURVN (unified; bump via scripts/release.sh)"

rm -rf "$UPSTREAM_DIR"
mv "$WORK/pristine" "$UPSTREAM_DIR"
rm -rf "$WORK"
echo "pinned to $TAG. Next: scripts/build-apk.sh $APP (cargo refreshes Cargo.lock automatically)."
